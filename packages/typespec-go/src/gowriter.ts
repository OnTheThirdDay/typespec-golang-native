/**
 * Minimal Go source assembly. Generated code is written so that it is already gofmt-formatted:
 * tabs for indentation and no column alignment (every struct field and constant is preceded by
 * a doc comment line, which ends gofmt alignment sections). Tests run `gofmt -l` on all output.
 */

import { formatDocComments } from "./doccomment.js";

const KNOWN_PACKAGES: Record<string, string> = {
  bytes: "bytes",
  context: "context",
  errors: "errors",
  fmt: "fmt",
  io: "io",
  iter: "iter",
  json: "encoding/json",
  big: "math/big",
  mime: "mime",
  multipart: "mime/multipart",
  http: "net/http",
  url: "net/url",
  regexp: "regexp",
  strings: "strings",
  time: "time",
};

export function validGoPath(path: string): boolean {
  return path.split("/").every(part => /^[A-Za-z0-9._~-]+$/.test(part) && !part.startsWith(".") && !part.endsWith("."));
}

/** Placeholder for a declaration name, resolved after all declarations are named. */
export function declRef(id: number): string {
  return `\u0000${id}\u0000`;
}

/** Placeholder for the package variable holding conversion codec `index` (named late). */
export function conversionRef(index: number): string {
  return `\u0002${index}\u0002`;
}

/** Placeholder for the text codec (tsgo.TextCodec) of a declaration with a text form. */
export function textRef(id: number): string {
  return `\u0001${id}\u0001`;
}

/**
 * Replaces declaration placeholders by names. An identifier glued to a placeholder (`New` in
 * `New<ref>`) is moved after the package qualifier of an external name (`pkg.NewName`). Text
 * codec placeholders become `texts(id)`, by default the declaration's own text functions.
 */
export function resolveDeclRefs(text: string, names: (id: number) => string, texts?: (id: number) => string | undefined, conversions?: (index: number) => string): string {
  const own = (id: number) => {
    const n = names(id);
    return `tsgo.TextCodec[${n}]{Format: ${n}.formatText, Parse: ${qualified("parse", n)}Text}`;
  };
  return text
    .replace(/\u0002(\d+)\u0002/g, (_m, i) => {
      if (!conversions) throw new Error("internal error: unresolved conversion codec");
      return conversions(Number(i));
    })
    .replace(/\u0001(\d+)\u0001/g, (_m, id) => texts?.(Number(id)) ?? own(Number(id)))
    .replace(/([A-Za-z_][A-Za-z0-9_]*)?\u0000(\d+)\u0000/g, (_m, pre: string | undefined, id) => (pre ? qualified(pre, names(Number(id))) : names(Number(id))));
}

/** `prefix` + name, keeping a package qualifier first (`pkg.Name` → `pkg.<prefix>Name`). */
function qualified(prefix: string, name: string): string {
  const i = name.lastIndexOf(".");
  return i < 0 ? prefix + name : name.slice(0, i + 1) + prefix + name.slice(i + 1);
}

export function goFile(pkg: string, body: string, runtimeImports: Record<string, string>): string {
  const scan = stripCommentsAndStrings(body);
  const std = new Set<string>();
  const other = new Map<string, string>(); // path → import name when it differs from the last element
  for (const m of scan.matchAll(/\b([a-z][A-Za-z0-9]*)\.[A-Za-z_]/g)) {
    const alias = m[1];
    const path = runtimeImports[alias];
    if (Object.hasOwn(KNOWN_PACKAGES, alias)) std.add(KNOWN_PACKAGES[alias]);
    else if (Object.hasOwn(runtimeImports, alias)) other.set(path, alias === "tsgo" && path.split("/").pop() === alias ? "" : alias + " "); // externalRef0 "example.com/shared"
  }
  let out = "// Code generated by typespec-go. DO NOT EDIT.\n\n";
  out += `package ${pkg}\n`;
  const groups = [[...std].sort().map((p) => `"${p}"`), [...other.keys()].sort().map((p) => `${other.get(p)}"${p}"`)].filter((g) => g.length);
  if (groups.length) {
    out += "\nimport (\n";
    out += groups.map((g) => g.map((p) => `\t${p}\n`).join("")).join("\n");
    out += ")\n";
  }
  // Doc comments of top-level declarations in gofmt's canonical form (go/doc/comment).
  const code = formatDocComments(body.replace(/^\s+/, "").replace(/\n{3,}/g, "\n\n").replace(/\s+$/, ""));
  // A file without declarations (models.go of a service without models) ends after its header.
  return code ? out + "\n" + code + "\n" : out;
}

function stripCommentsAndStrings(s: string): string {
  return s
    .replace(/`[^`]*`/g, "``")
    .replace(/"(?:[^"\\\n]|\\.)*"/g, '""')
    .replace(/\/\/[^\n]*/g, "");
}

const LS = new RegExp(String.fromCharCode(0x2028), "g");
const PS = new RegExp(String.fromCharCode(0x2029), "g");

/** Go string literal. */
export function goString(s: string): string {
  return JSON.stringify(s).replace(LS, "\\u2028").replace(PS, "\\u2029");
}

/** Go raw string literal when possible (regular expressions), otherwise an interpreted literal. */
export function goRawString(s: string): string {
  return s.includes("`") || /[\r\u0000]/.test(s) ? goString(s) : "`" + s + "`";
}

/** Formats documentation as Go comment lines prefixed with indentation. */
export function docComment(text: string | undefined, indent = ""): string {
  if (!text) return "";
  return (
    text
      .split(/\r?\n/)
      .map((l) => `${indent}//${l.trim() ? " " + l.trimEnd() : ""}`)
      .join("\n") + "\n"
  );
}

/** Small helper to build indented code. */
export class Code {
  private lines: string[] = [];
  private depth = 0;
  /** Depths of open `switch` blocks: their case clauses and "\t"-prefixed bodies are dedented. */
  private switches: number[] = [];

  line(s = ""): this {
    let depth = this.depth;
    if (this.switches[this.switches.length - 1] === this.depth && (/^(case\b.*|default):/.test(s) || s.startsWith("\t"))) depth--;
    this.lines.push(s === "" ? "" : "\t".repeat(depth) + s);
    return this;
  }
  lines_(ss: string[]): this {
    for (const s of ss) this.line(s);
    return this;
  }
  open(s: string): this {
    this.line(s);
    this.depth++;
    if (/^switch/.test(s)) this.switches.push(this.depth);
    return this;
  }
  close(s = "}"): this {
    if (this.switches[this.switches.length - 1] === this.depth) this.switches.pop();
    this.depth--;
    this.line(s);
    return this;
  }
  /** A line that closes and reopens a block at the same depth, e.g. "} else {". */
  mid(s: string): this {
    this.depth--;
    this.line(s);
    this.depth++;
    return this;
  }
  /** Raw multi-line text, re-indented at the current depth. */
  raw(text: string): this {
    for (const l of text.replace(/\n$/, "").split("\n")) this.line(l);
    return this;
  }
  toString(): string {
    return this.lines.join("\n") + "\n";
  }
}
